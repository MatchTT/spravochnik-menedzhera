import docx as _docx, html as _html
def _runs(p):
    out = ''
    for r in p.runs:
        t = _html.escape(r.text)
        out += f'<b>{t}</b>' if r.bold else t
    return out
_d = _docx.Document('/mnt/user-data/uploads/e7bbb04c-Shablony_Salesbot_reg1.docx')
_body = ''
_tpl_open = False
_buf = []
def _flush():
    global _body, _buf, _tpl_open
    if _buf:
        txt = '\n\n'.join(_buf)
        _body += f'<div class="tpl"><div class="tpl-h"><div class="tpl-t">{_label}</div><button class="copy">Копировать</button></div><div class="tpl-text">{txt}</div></div>'
        _buf = []
_label = ''
_intro_done = False
for p in _d.paragraphs:
    if not p.text.strip():
        continue
    st = p.style.name
    if st == 'Title':
        continue
    if st == 'Normal':
        _body += f'<p>{_runs(p)}</p>'
        if not _intro_done and 'Документ содержит' in p.text:
            t = _d.tables[0]
            _body += '<table>' + ''.join('<tr>' + ''.join((f'<th>{_html.escape(c.text)}</th>' if i == 0 else f'<td>{_html.escape(c.text)}</td>') for c in r.cells) + '</tr>' for i, r in enumerate(t.rows)) + '</table>'
            _intro_done = True
    elif st == 'Heading 1':
        _flush(); _body += f'<h2>{_html.escape(p.text)}</h2>'
    elif st == 'Heading 2':
        _flush(); _body += f'<h3>{_html.escape(p.text)}</h3>'
    elif st == 'Template Label':
        _flush(); _label = _html.escape(p.text)
    elif st == 'Template Text':
        _buf.append(_html.escape(p.text))
    else:
        _body += f'<p>{_runs(p)}</p>'
_flush()

